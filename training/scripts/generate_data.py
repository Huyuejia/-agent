def _fill_template(template: str, use_test: bool = False) -> str:
    """替换模板中的占位符为随机产品名/场景值。"""
    products_pool = FLAT_TEST_PRODUCTS if use_test else FLAT_TRAIN_PRODUCTS
    text = template
    text = text.replace("{product}", random.choice(products_pool))
    text = text.replace("{product_a}", random.choice(products_pool))
    b = random.choice(products_pool)
    while b == text:  # 避免 a == b
        b = random.choice(products_pool)
    text = text.replace("{product_b}", b)
    scenarios = ["客厅", "卧室", "厨房", "阳台", "玄关", "卫生间", "书房", "商铺", "办公室",
                 "车库", "地下室", "走廊", "儿童房", "老人房", "出租房", "别墅", "公寓"]
    text = text.replace("{scenario}", random.choice(scenarios))
    return text


def generate_samples(
    templates: dict[str, list[str]],
    count_per_label: int,
    use_test_products: bool = False,
    exclude_templates: dict[str, set[str]] | None = None,
) -> list[dict[str, str]]:
    """从模板池生成样本，每类标签取 count_per_label 条。
    自动跳过生成后文本过短 (< 5 chars) 的样本并重试。
    exclude_templates 用于阻止使用某些模板（防泄漏）。
    """
    samples: list[dict[str, str]] = []
    MIN_TEXT_LEN = 5

    for label in LABELS:
        pool = templates[label]
        excluded = exclude_templates.get(label, set()) if exclude_templates else set()
        available_pool = [t for t in pool if t not in excluded]
        if not available_pool:
            available_pool = pool  # fallback

        used: set[str] = set()
        for _ in range(count_per_label):
            while True:
                available = [t for t in available_pool if t not in used]
                if not available:
                    used.clear()
                    available = available_pool
                template = random.choice(available)
                text = _fill_template(template, use_test=use_test_products)
                if len(text) >= MIN_TEXT_LEN:
                    used.add(template)
                    samples.append({"text": text, "label": label})
                    break
    return samples


def _filter_short_templates(
    templates: dict[str, list[str]], min_len: int = 5
) -> dict[str, list[str]]:
    """过滤掉生成后始终短于 min_len 的模板（无占位符的短句）。"""
    filtered: dict[str, list[str]] = {}
    for label, pool in templates.items():
        keep = []
        for t in pool:
            # 有占位符的模板填充后大概率够长；无占位符的检查长度
            if "{" in t or len(t) >= min_len:
                keep.append(t)
        if not keep:
            keep = pool  # 兜底
        filtered[label] = keep
    return filtered


