def main() -> None:
    random.seed(42)  # 可复现

    data_dir = Path(__file__).resolve().parent.parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    # 预先过滤所有模板池中的过短模板（避免死循环）
    TRAIN_TEMPLATES_F = _filter_short_templates(TRAIN_TEMPLATES)
    TEST_TEMPLATES_F = _filter_short_templates(TEST_TEMPLATES)

    # 将 TRAIN_TEMPLATES 每类拆分为 train 专用 / val 专用，避免泄漏
    train_templates: dict[str, list[str]] = {}
    val_templates: dict[str, list[str]] = {}
    train_used: dict[str, set[str]] = {}

    for label in LABELS:
        pool = list(TRAIN_TEMPLATES_F[label])  # copy
        random.shuffle(pool)
        split = max(int(len(pool) * 0.75), 20)  # 至少 20 条给 val
        train_templates[label] = pool[:split]
        val_templates[label] = pool[split:]
        train_used[label] = set()

    # train: 90/类
    train = generate_samples(train_templates, 90, use_test_products=False)
    random.shuffle(train)

    # validation: 20/类（使用 val_templates，排除 train 已用模板）
    val_exclude = {lab: set(train_templates[lab]) for lab in LABELS}
    val = generate_samples(val_templates, 20, use_test_products=False,
                          exclude_templates=val_exclude)
    random.shuffle(val)

    # test: 20/类（使用 test 模板池 + test 产品池）
    test = generate_samples(TEST_TEMPLATES_F, 20, use_test_products=True)
    random.shuffle(test)

    for name, data in [("train", train), ("validation", val), ("test", test)]:
        path = data_dir / f"{name}.jsonl"
        with open(path, "w", encoding="utf-8") as f:
            for item in data:
                f.write(json.dumps(item, ensure_ascii=False) + "\n")
        print(f"[OK] {path}  — {len(data)} samples")

    # 汇总
    print(f"\n总计: train={len(train)}, val={len(val)}, test={len(test)}")


if __name__ == "__main__":
    main()
